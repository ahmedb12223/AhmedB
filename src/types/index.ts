export type LanguageTrack = 'all' | 'english' | 'arabic';

export interface Student {
  id: string;
  name: string; // e.g. "عمر طارق فاروق" or "Adam Hesham"
  classId: string;
  track: 'english' | 'arabic'; // English (Languages) or Arabic
  studentCode?: string;
  parentPhone?: string;
}

export interface WhatsAppGroupConfig {
  id: string;
  name?: string; // e.g. "جروب أمهات Grade 4", "جروب الطلاب"
  recipient: string; // phone (+966...) or group ID/link (chat.whatsapp.com/...)
  recipientType?: 'phone' | 'group';
}

export interface SchoolClass {
  id: string;
  name: string; // e.g. "GR4 - A", "GR4 - B", "7A"
  gradeLevel: string; // e.g. "Grade 4"
  zoomUrl?: string; // Zoom meeting link linked to this class
  description?: string;
  whatsappRecipient?: string; // phone number (+966...) or WhatsApp group id/link
  whatsappRecipientType?: 'phone' | 'group';
  whatsappGroups?: WhatsAppGroupConfig[]; // Multiple linked WhatsApp groups/numbers
  createdAt: string;
}

export interface AttendanceRecord {
  id: string;
  sessionId: string;
  studentId?: string; // matched student id, or undefined if guest
  studentName: string; // entered name
  matchedRosterName?: string; // official matched name in roster
  track?: 'english' | 'arabic';
  timestamp: string; // ISO string (first join)
  lastJoinedAt?: string; // ISO string (latest re-entry join)
  joinCount?: number; // number of times re-entered
  deviceFingerprint?: string;
  status: 'present' | 'late' | 'guest';
  confidenceScore: number; // 0 to 1
}

export interface ClassSession {
  id: string;
  teacherId: string;
  classId: string;
  className: string;
  sessionTitle: string;
  zoomUrl: string;
  targetTrack: LanguageTrack; // 'all' | 'english' | 'arabic'
  createdAt: string;
  scheduledTime?: string;
  isActive: boolean;
  attendance: AttendanceRecord[];
  whatsappReminderSent?: boolean;
  reminderSentAt?: string;
  autoGenerated?: boolean;
  lastAttendanceResetAt?: string;
}

export type DayOfWeek = 'sunday' | 'monday' | 'tuesday' | 'wednesday' | 'thursday' | 'friday' | 'saturday';

export interface SchedulePeriod {
  id: string;
  dayOfWeek: DayOfWeek;
  dayNameArabic: string; // e.g. "الأحد", "الإثنين"
  className: string; // e.g. "Grade 4 - A"
  classId?: string;
  startTime: string; // "09:00" or "10:15"
  endTime?: string;
  subject?: string;
  targetTrack?: LanguageTrack;
  zoomUrl?: string;
}

export interface TeacherProfile {
  id: string;
  name: string; // e.g. "أ. أحمد مصطفى"
  subject: string; // e.g. "Science & Biology / علوم ولغات"
  schoolName: string; // e.g. "مدرسة الأمل الرسمية المتميزة للغات"
  email: string;
  defaultZoomLink?: string;
  assignedClassIds: string[]; // Classes this teacher teaches
  avatarUrl?: string;
  weeklySchedule?: SchedulePeriod[];
  classWhatsAppGroups?: Record<string, WhatsAppGroupConfig[]>; // Class ID -> linked WhatsApp groups/numbers for this teacher
  classZoomLinks?: Record<string, string>; // Class ID -> Zoom link specific to this teacher
  whatsappConfig?: WhatsAppSessionState; // Teacher-specific WhatsApp provider and template settings
}

export interface WhatsAppLog {
  id: string;
  sessionId?: string;
  className: string;
  recipient: string;
  recipientType: 'phone' | 'group';
  sentAt: string;
  status: 'sent' | 'failed';
  messagePreview: string;
  triggerType: 'auto_5min' | 'manual';
}

export type WhatsAppProvider = 'green_api' | 'ultramsg' | 'meta' | 'meta_cloud' | 'webhook' | 'direct';

export interface WhatsAppSessionState {
  status: 'disconnected' | 'connecting' | 'connected';
  phoneNumber?: string;
  connectedAt?: string;
  qrCode?: string;
  batteryLevel?: number;
  autoRemindEnabled: boolean;
  reminderMinutesBefore: number; // default 5
  webhookUrl?: string;
  provider?: WhatsAppProvider;
  greenApiInstanceId?: string;
  greenApiToken?: string;
  ultraMsgInstanceId?: string;
  ultraMsgToken?: string;
  metaPhoneNumberId?: string;
  metaAccessToken?: string;
  lastVerifiedAt?: string;
  connectionError?: string;
  customMessageTemplate?: string;
}

